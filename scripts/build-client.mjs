// Builds dist/client.js from src/client/*.js fragments.
//
// The Web module loader expects one file that registers a factory under the exact
// package name. Fragments are plain JavaScript function/var declarations written
// for `mode: sloppy` inside one factory scope, so no bundler is required.
//
// Usage: node scripts/build-client.mjs

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
const ORDER = ['shared.js', 'chart.js', 'page.js', 'dock.js', 'main.js']

const parts = []
for (const file of ORDER) {
  let text
  try {
    text = await readFile(ROOT + 'src/client/' + file, 'utf8')
  } catch {
    console.error(`✗ missing fragment: src/client/${file}`)
    process.exitCode = 1
    throw new Error(`missing fragment ${file}`)
  }
  if (/^\s*(import|export)\s/m.test(text)) {
    console.error(`✗ src/client/${file} must not use import/export (single factory scope)`)
    process.exitCode = 1
    throw new Error(`import/export in ${file}`)
  }
  parts.push(`\n/* ============================== ${file} ============================== */\n` + text.trim() + '\n')
}

const body = parts.join('\n')

// Parse-only check: the fragments are a function body (main.js ends with `return`).
try {
  new Function(body)
} catch (error) {
  console.error('✗ client fragment syntax error:', error && error.message)
  process.exitCode = 1
  throw error
}

// Soft contract checks: the fragment owners must provide these exact names.
const REQUIRED = [
  ['shared', 'DSHTOKEN_BASE_CSS'],
  ['shared', 'DSHTOKEN_I18N'],
  ['chart', 'DSHTOKEN_I18N_CHART'],
  ['chart', 'DshTokenChart'],
  ['page', 'DSHTOKEN_I18N_PAGE'],
  ['page', 'DshTokenPage'],
  ['dock', 'DSHTOKEN_I18N_DOCK'],
  ['dock', 'DshTokenUsageDock'],
  ['main', 'DshTokenApply'],
]
for (const [fragment, name] of REQUIRED) {
  if (!new RegExp('\\b' + name + '\\b').test(body)) {
    console.error(`✗ missing required identifier ${name} (expected from ${fragment}.js)`)
    process.exitCode = 1
  }
}
const forbidden = body.match(/require\((?:'|")(@deepseek-ai\/[^'"]+)(?:'|")\)/g)
if (forbidden) {
  console.error('✗ client fragments must not require Harness Client packages:', forbidden.join(', '))
  process.exitCode = 1
}
if (/^\s*import\s/m.test(body) || /^\s*export\s/m.test(body)) {
  console.error('✗ client fragments must not use import/export')
  process.exitCode = 1
}

const pkg = JSON.parse(await readFile(ROOT + 'package.json', 'utf8'))
const out = `/* Generated by scripts/build-client.mjs — edit src/client/*.js instead. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var React = require('react');
    var h = React.createElement;
${body}
  },
});
`

await mkdir(ROOT + 'dist', { recursive: true })
await writeFile(ROOT + 'dist/client.js', out, 'utf8')
console.log(`✓ Built dist/client.js  ${out.length} bytes  (${ORDER.length} fragments)`)
